import React, { useState } from 'react';
import { Info } from 'lucide-react';

interface CompatibilityBadgeProps {
  score: number;
  size?: 'sm' | 'md' | 'lg';
  showTooltip?: boolean;
  className?: string;
}

export const CompatibilityBadge: React.FC<CompatibilityBadgeProps> = ({
  score,
  size = 'md',
  showTooltip = true,
  className = ''
}) => {
  const [isTooltipOpen, setIsTooltipOpen] = useState(false);

  const sizeClasses = {
    sm: 'text-xs px-2.5 py-1 gap-1.5',
    md: 'text-xs px-3.5 py-1.5 gap-2',
    lg: 'text-sm px-4 py-2 gap-2.5'
  };

  return (
    <div className={`relative inline-flex items-center ${className}`}>
      <div
        className={`inline-flex items-center font-medium rounded-full bg-[#141216]/95 text-white border border-[#C41527]/50 shadow-[0_0_15px_rgba(179,0,27,0.35)] backdrop-blur-md transition-all duration-300 hover:border-[#C41527] ${sizeClasses[size]}`}
      >
        <span className="w-2 h-2 rounded-full bg-[#C41527] animate-pulse" />
        <span className="font-semibold text-[#C41527]">{score}%</span>
        <span className="text-zinc-200">Predicted Compatibility</span>
        
        {showTooltip && (
          <button
            type="button"
            onMouseEnter={() => setIsTooltipOpen(true)}
            onMouseLeave={() => setIsTooltipOpen(false)}
            onClick={(e) => {
              e.stopPropagation();
              setIsTooltipOpen(!isTooltipOpen);
            }}
            className="text-zinc-400 hover:text-white transition-colors ml-0.5"
            aria-label="Information regarding compatibility prediction"
          >
            <Info className="w-3.5 h-3.5" />
          </button>
        )}
      </div>

      {/* Informational Tooltip */}
      {showTooltip && isTooltipOpen && (
        <div className="absolute bottom-full left-1/2 -translate-x-1/2 mb-2 w-64 p-2.5 rounded-xl bg-[#141216] border border-[#8B0000]/40 text-xs text-zinc-300 shadow-2xl z-40 text-center animate-in fade-in duration-150 backdrop-blur-xl">
          <p className="leading-snug">
            An estimate generated by our compatibility model. It is not a guarantee of relationship success.
          </p>
          <div className="absolute top-full left-1/2 -translate-x-1/2 border-4 border-transparent border-t-[#141216]" />
        </div>
      )}
    </div>
  );
};
